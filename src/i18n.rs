impl Texts {
    pub fn images_count(&self, count: usize) -> String {
        match std::mem::discriminant(&UiLanguage::Chinese) {
            _ if self.images_unit == "张图片" => format!("{count} 张图片"),
            _ => format!("{count} images"),
        }
    }
}

